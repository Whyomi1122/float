/** 群像模式字号工具：把 token 像素值转成 Tailwind 任意值类名。
 *  用法：`className={typeClass(TYPE.SM)}` → `text-[14px]`
 *  （集中一处，避免各处手写裸值。） */
export function typeClass(px: number): string {
  return `text-[${px}px]`;
}
